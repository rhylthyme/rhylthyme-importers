"""
Regenerate the auto-generated sections of ``docs/opentrons.md``.

Currently regenerates one block:

- **Duration model reference table** — every entry of
  :data:`opentrons.duration_model.DURATION_SECONDS`, in a markdown
  table, between marker comments. The Python dict is the single
  source of truth; this script keeps the markdown in sync so a
  contributor never needs to edit the table by hand.

Usage::

    python -m rhylthyme_importers.opentrons.docs_gen        # rewrite docs in-place
    python -m rhylthyme_importers.opentrons.docs_gen --check  # exit non-zero if regenerated docs differ

Wire ``--check`` into CI to catch drift before it ships.
"""

