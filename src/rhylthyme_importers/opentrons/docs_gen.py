def _render_table() -> str:
    """Build the markdown table from ``DURATION_SECONDS``."""
    lines = [
        '| Command type | Seconds | Notes |',
        '|---|---:|---|',
    ]
    for ct in sorted(DURATION_SECONDS.keys()):
        secs = DURATION_SECONDS[ct]
        note = _NOTES.get(ct, '')
        lines.append(f'| `{ct}` | {secs} | {note} |')
    return '\n'.join(lines)


def _splice(existing: str, replacement: str) -> str:
    """Replace the content between the markers with ``replacement``.

    Adds the markers + replacement at the end of the file if they're
    missing, so first-run wiring doesn't need a separate command.
    """
    block = f'{_START_MARKER}\n\n{replacement}\n\n{_END_MARKER}'
    if _START_MARKER not in existing or _END_MARKER not in existing:
        # Append at the bottom under a fresh heading.
        appendix = (
            f'\n\n## Duration model reference (auto-generated)\n\n'
            f'_Regenerate with `make docs` after editing `DURATION_SECONDS` in '
            f'`opentrons/duration_model.py`._\n\n{block}\n'
        )
        return existing.rstrip() + appendix
    pattern = re.compile(
        re.escape(_START_MARKER) + r'.*?' + re.escape(_END_MARKER),
        re.DOTALL,
    )
    return pattern.sub(block, existing, count=1)


def run(check_only: bool = False) -> int:
    docs = DOCS_PATH
    if not docs.exists():
        sys.stderr.write(f'error: docs file not found: {docs}\n')
        return 2
    existing = docs.read_text(encoding='utf-8')
    regen = _splice(existing, _render_table())
    if check_only:
        if regen == existing:
            print('docs are up to date.')
            return 0
        diff = difflib.unified_diff(
            existing.splitlines(keepends=True),
            regen.splitlines(keepends=True),
            fromfile='docs/opentrons.md (current)',
            tofile='docs/opentrons.md (regenerated)',
            n=2,
        )
        sys.stderr.write('docs are out of date. Run `make docs` and commit the result.\n')
        sys.stderr.writelines(diff)
        return 1
    docs.write_text(regen, encoding='utf-8')
    print(f'wrote {docs}')
    return 0


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true',
                   help='exit non-zero if docs are out of date (CI mode)')
    args = p.parse_args()
    sys.exit(run(check_only=args.check))


if __name__ == '__main__':
    main()
